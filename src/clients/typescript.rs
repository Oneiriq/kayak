//! The TypeScript client generator.

use std::fmt::Write as _;

use surql::schema::{FieldType, TableDefinition};

use crate::ir::{ActionOutput, Contract};
use crate::naming::{camel, singular, snake, type_name};
use crate::openapi::GenerateError;

use super::{
    checked, column, query_kind, query_params, query_takes_id, sub_method_stem, sub_table,
    sub_type_name,
};

pub fn generate_client_ts(
    contract: &Contract,
    schema: &[TableDefinition],
) -> Result<String, GenerateError> {
    let resources = checked(contract, schema)?;
    let prefix = contract.prefix();
    let mut out = String::new();
    writeln!(
        out,
        "// Generated by janus for the `{}` contract v{}. Do not edit.\n",
        contract.name, contract.version,
    )
    .unwrap();

    for (resource, table) in &resources {
        ts_interface(
            &mut out,
            &type_name(&resource.name),
            &resource.fields,
            table,
        );
        for sub in &resource.sub_resources {
            ts_interface(
                &mut out,
                &sub_type_name(resource, sub),
                &sub.fields,
                sub_table(schema, sub),
            );
        }
    }

    // The credential the contract declared, in the one place every
    // request funnels through.
    let credential = contract.auth.credential_name();
    let param = credential.map_or_else(String::new, |name| format!(", private {name}: string"));
    let header = match contract.auth.header() {
        Some((name, prefix)) => {
            let value = credential.expect("a header scheme names its credential");
            // A template literal only where there is a prefix to join;
            // `\u{60}${this.tenant}\u{60}` for a bare value is noise.
            if prefix.is_empty() {
                format!("        '{name}': this.{value},\n")
            } else {
                format!("        '{name}': `{prefix}${{this.{value}}}`,\n")
            }
        }
        None => String::new(),
    };
    writeln!(
        out,
        "export class Client {{\n\
         \x20 constructor(private baseUrl: string{param}) {{}}\n\n\
         \x20 private async request<T>(method: string, path: string, body?: unknown): Promise<T> {{\n\
         \x20   const response = await fetch(`${{this.baseUrl}}${{path}}`, {{\n\
         \x20     method,\n\
         \x20     headers: {{\n\
         {header}\
         \x20       ...(body === undefined ? {{}} : {{ 'content-type': 'application/json' }}),\n\
         \x20     }},\n\
         \x20     body: body === undefined ? undefined : JSON.stringify(body),\n\
         \x20   }})\n\
         \x20   if (!response.ok) throw new Error(`${{method}} ${{path}}: ${{response.status}}`)\n\
         \x20   if (response.status === 204) return undefined as T\n\
         \x20   return (await response.json()) as T\n\
         \x20 }}\n",
    )
    .unwrap();

    for (resource, _) in &resources {
        let name = type_name(&resource.name);
        let list_fn = camel(&format!("list_{}", snake(&resource.name)));
        let get_fn = camel(&format!("get_{}", snake(&singular(&resource.name))));
        if resource.faces.list {
            writeln!(
                out,
                "  {list_fn}(limit?: number, cursor?: string): Promise<{name}Page> {{"
            )
            .unwrap();
            writeln!(
                out,
                "    const query = new URLSearchParams()\n\
                 \x20   if (limit !== undefined) query.set('limit', String(limit))\n\
                 \x20   if (cursor !== undefined) query.set('cursor', cursor)\n\
                 \x20   const suffix = query.size > 0 ? `?${{query}}` : ''\n\
                 \x20   return this.request('GET', `{prefix}/{}${{suffix}}`)",
                resource.name,
            )
            .unwrap();
            out.push_str("  }\n\n");
        }
        if resource.faces.get {
            writeln!(out, "  {get_fn}(id: string): Promise<{name}> {{").unwrap();
            writeln!(
                out,
                "    return this.request('GET', `{prefix}/{}/${{id}}`)",
                resource.name,
            )
            .unwrap();
            out.push_str("  }\n\n");
        }

        for sub in &resource.sub_resources {
            let sub_name = sub_type_name(resource, sub);
            writeln!(
                out,
                "  {stem}(id: string, limit?: number, cursor?: string): Promise<{sub_name}Page> {{",
                stem = camel(&sub_method_stem(resource, sub)),
            )
            .unwrap();
            writeln!(
                out,
                "    const query = new URLSearchParams()
                     if (limit !== undefined) query.set('limit', String(limit))
                     if (cursor !== undefined) query.set('cursor', cursor)
                     const suffix = query.size > 0 ? `?${{query}}` : ''
                     return this.request('GET', `{prefix}/{}/${{id}}/{}${{suffix}}`)",
                resource.name, sub.name,
            )
            .unwrap();
            out.push_str(
                "  }

",
            );
        }
        for action in &resource.actions {
            let method_fn = camel(&format!(
                "{}_{}",
                snake(&action.name),
                snake(&singular(&resource.name)),
            ));
            let mut parameters = Vec::new();
            if action.takes_id() {
                parameters.push("id: string".to_owned());
            }
            if !action.input.is_empty() {
                parameters.push("input: Record<string, unknown>".to_owned());
            }
            let output = match action.output {
                ActionOutput::Resource => name.clone(),
                ActionOutput::Json => "Record<string, unknown>".to_owned(),
                ActionOutput::None => "void".to_owned(),
            };
            let path = action.path.replace("{id}", "${id}");
            let body_argument = if action.input.is_empty() {
                ""
            } else {
                ", input"
            };
            writeln!(
                out,
                "  {method_fn}({}): Promise<{output}> {{",
                parameters.join(", "),
            )
            .unwrap();
            writeln!(
                out,
                "    return this.request('{}', `{prefix}/{}{path}`{body_argument})",
                action.method, resource.name,
            )
            .unwrap();
            out.push_str("  }\n\n");
        }
    }
    // Queries reach REST as GETs carrying their inputs in the query
    // string. They declare no output shape, so the method answers with
    // open JSON.
    for query in &contract.queries {
        let mut parameters = Vec::new();
        if query_takes_id(query) {
            parameters.push("id: string".to_owned());
        }
        for field in query_params(query) {
            let kind = query_kind(field.kind, "ts");
            parameters.push(if field.required {
                format!("{}: {kind}", camel(&field.name))
            } else {
                format!("{}?: {kind}", camel(&field.name))
            });
        }
        writeln!(
            out,
            "  {}({}): Promise<unknown> {{",
            camel(&query.name),
            parameters.join(", "),
        )
        .unwrap();
        let path = query.path.replace("{id}", "${id}");
        if query_params(query).is_empty() {
            // Nothing to encode, so nothing is built.
            writeln!(out, "    return this.request('GET', `{path}`)").unwrap();
        } else {
            out.push_str("    const query = new URLSearchParams()\n");
            for field in query_params(query) {
                let name = &field.name;
                let binding = camel(name);
                if field.required {
                    writeln!(out, "    query.set('{name}', String({binding}))").unwrap();
                } else {
                    writeln!(
                        out,
                        "    if ({binding} !== undefined) query.set('{name}', String({binding}))",
                    )
                    .unwrap();
                }
            }
            out.push_str("    const suffix = query.size > 0 ? `?${query}` : ''\n");
            writeln!(out, "    return this.request('GET', `{path}${{suffix}}`)").unwrap();
        }
        out.push_str("  }\n\n");
    }
    out.push_str("}\n");
    Ok(out)
}

fn ts_interface(
    out: &mut String,
    name: &str,
    fields: &[crate::ir::FieldExposure],
    table: &TableDefinition,
) {
    writeln!(out, "export interface {name} {{").unwrap();
    writeln!(out, "  id: string").unwrap();
    for exposure in fields {
        let field = column(table, &exposure.column);
        let base = match field.field_type {
            FieldType::Int | FieldType::Float | FieldType::Decimal | FieldType::Number => "number",
            FieldType::Bool => "boolean",
            FieldType::Object | FieldType::Array | FieldType::Geometry | FieldType::Any => {
                "unknown"
            }
            _ => "string",
        };
        let optional = if field.nullable || exposure.guard.is_some() {
            "?"
        } else {
            ""
        };
        writeln!(out, "  {}{optional}: {base}", camel(exposure.api_name())).unwrap();
    }
    writeln!(out, "}}\n").unwrap();
    writeln!(out, "export interface {name}Page {{").unwrap();
    writeln!(out, "  items: {name}[]").unwrap();
    writeln!(out, "  next_cursor?: string | null").unwrap();
    writeln!(out, "}}\n").unwrap();
}
